package com.situmorangit.tmbbmoviesmandiri.ui

import androidx.lifecycle.ViewModel
import androidx.lifecycle.ViewModelProvider
import com.situmorangit.tmbbmoviesmandiri.data.repository.MovieRepository
import com.situmorangit.tmbbmoviesmandiri.ui.detail.MovieDetailViewModel
import com.situmorangit.tmbbmoviesmandiri.ui.genre.GenreViewModel
import com.situmorangit.tmbbmoviesmandiri.ui.movie.MovieListViewModel

class GenreViewModelFactory(private val repository: MovieRepository) : ViewModelProvider.Factory {
    override fun <T : ViewModel> create(modelClass: Class<T>): T {
        if (modelClass.isAssignableFrom(GenreViewModel::class.java)) {
            @Suppress("UNCHECKED_CAST")
            return GenreViewModel(repository) as T
        }
        throw IllegalArgumentException("Unknown ViewModel class")
    }
}

